// The PDF export: the same record as the Markdown one, plus the picture, and
// it must actually paginate rather than stop at page one.

import Foundation
import GutenbergKGKit
import PDFKit
import Testing

@testable import KnowledgePressUI

#if canImport(UIKit)
    import UIKit
#elseif canImport(AppKit)
    import AppKit
#endif

@Suite("Conversation PDF export")
@MainActor
struct ConversationPDFTests {

    private func hit(_ n: Int) -> Hit {
        let json = """
            {"node_id":"gutenberg:chunk_\(n)","name":"Inferno","kind":"chunk",
             "score":0.8\(n),"kg_name":"world-literature","kg_kind":"DocKG",
             "title":"The Divine Comedy","author":"Dante Alighieri","genre":"world-literature",
             "summary":null,"source_path":"x.md","timestamp":null,
             "content":"Midway upon the journey of our life I found myself within a forest dark."}
            """
        return try! JSONDecoder().decode(Hit.self, from: Data(json.utf8))
    }

    private func turn(_ question: String) -> ChatTurn {
        var turn = ChatTurn(question: question, corpus: "world-literature", engine: .onDevice)
        turn.retrieval = RetrievalResult(hits: (1...6).map(hit), kgsQueried: 3, searchMs: 42)
        turn.answer = String(
            repeating: "Dante's Hell is arranged in **nine** concentric *circles*. ", count: 40)
        return turn
    }

    /// A plain 64x48 PNG, so the attachment path is exercised.
    private func png() -> Data {
        #if canImport(UIKit)
            UIGraphicsImageRenderer(size: CGSize(width: 64, height: 48)).pngData { context in
                UIColor.orange.setFill()
                context.fill(CGRect(x: 0, y: 0, width: 64, height: 48))
            }
        #else
            let image = NSImage(size: NSSize(width: 64, height: 48), flipped: false) { rect in
                NSColor.orange.setFill()
                rect.fill()
                return true
            }
            return NSBitmapImageRep(data: image.tiffRepresentation!)!
                .representation(using: .png, properties: [:])!
        #endif
    }

    @Test("a long chat paginates and keeps its text")
    func paginates() throws {
        let conversation = Conversation(
            title: "circles of Hell", turns: (1...4).map { turn("question \($0)") })
        // KP_PDF_IMAGE swaps in a real illustration when eyeballing KP_PDF_OUT.
        let picture = ProcessInfo.processInfo.environment["KP_PDF_IMAGE"]
            .flatMap { try? Data(contentsOf: URL(fileURLWithPath: $0)) } ?? png()
        let data = ConversationPDF.render(conversation) { _ in picture }

        if let dir = ProcessInfo.processInfo.environment["KP_PDF_OUT"] {
            try data.write(to: URL(fileURLWithPath: dir).appendingPathComponent("sample.pdf"))
        }

        let document = try #require(PDFDocument(data: data))
        #expect(document.pageCount > 1)
        let text = document.string ?? ""
        #expect(text.contains("circles of Hell"))
        #expect(text.contains("question 4"))
        #expect(text.contains("Dante Alighieri"))
        #expect(text.contains("Generated by The Knowledge Press"))
    }

    @Test("paper is Letter in the US and A4 elsewhere")
    func paperSize() throws {
        let conversation = Conversation(title: "circles of Hell", turns: [turn("question")])
        for (id, size) in [("en_US", ConversationPDF.letter), ("en_GB", ConversationPDF.a4)] {
            let data = ConversationPDF.render(
                conversation, image: { _ in nil }, locale: Locale(identifier: id))
            let page = try #require(PDFDocument(data: data)?.page(at: 0))
            #expect(page.bounds(for: .mediaBox).size == size)
        }
    }

    @Test("the filename is the Markdown one with a .pdf extension")
    func filename() {
        let conversation = Conversation(title: "circles of Hell", turns: [])
        #expect(ConversationPDF.filename(for: conversation) == "circles-of-Hell.pdf")
    }
}
