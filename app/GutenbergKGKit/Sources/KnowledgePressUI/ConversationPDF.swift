// A conversation as a PDF: the Markdown export's content, plus each turn's
// illustration, on US Letter or A4 pages by the reader's locale.
//
// Same record as ConversationMarkdown -- question, provenance, answer, the
// quoted passages with work, author and score -- because a PDF without its
// evidence is no more honest than a Markdown file without it. The only thing
// it adds is the picture, which a single .md file cannot carry.
//
// TextKit 1 does the pagination on both platforms: one text container per
// page, filled until the layout manager runs out of glyphs. It draws image
// attachments itself, so there is no web view to load and wait for.

import Foundation
import GutenbergKGKit

#if canImport(UIKit)
    import UIKit
    private typealias PlatformFont = UIFont
    private typealias PlatformColor = UIColor
    private typealias PlatformImage = UIImage
#elseif canImport(AppKit)
    import AppKit
    private typealias PlatformFont = NSFont
    private typealias PlatformColor = NSColor
    private typealias PlatformImage = NSImage
#endif

@MainActor
enum ConversationPDF {

    static let letter = CGSize(width: 612, height: 792)
    static let a4 = CGSize(width: 595, height: 842)
    static let margin: CGFloat = 54

    /// US Letter where the reader measures in inches, A4 everywhere else.
    static func pageSize(for locale: Locale) -> CGSize {
        locale.measurementSystem == .us ? letter : a4
    }

    private static func contentSize(_ pageSize: CGSize) -> CGSize {
        CGSize(width: pageSize.width - 2 * margin, height: pageSize.height - 2 * margin)
    }

    /// Render a whole conversation.
    ///
    /// :param conversation: The chat to render.
    /// :param image: PNG (or any image) bytes for a turn's illustration, or
    ///     nil when the turn has none.
    /// :param dateStyle: Formatter for the header date.
    /// :param locale: Picks the paper size.
    /// :returns: PDF data, one or more pages.
    static func render(
        _ conversation: Conversation,
        image: (ChatTurn) -> Data?,
        dateStyle: Date.FormatStyle = .dateTime.year().month().day(),
        locale: Locale = .current
    ) -> Data {
        let page = pageSize(for: locale)
        return paginate(
            document(conversation, image: image, dateStyle: dateStyle, page: page), page: page)
    }

    /// A filename for the exported document: the Markdown one, as `.pdf`.
    static func filename(for conversation: Conversation) -> String {
        let markdown = ConversationMarkdown.filename(for: conversation)
        return String(markdown.dropLast(".md".count)) + ".pdf"
    }

    // MARK: - The document

    private static let body = PlatformFont.systemFont(ofSize: 11)
    private static let gray = PlatformColor.gray

    private static func document(
        _ conversation: Conversation,
        image: (ChatTurn) -> Data?,
        dateStyle: Date.FormatStyle,
        page: CGSize
    ) -> NSAttributedString {
        let out = NSMutableAttributedString()
        out.append(paragraph(conversation.title, font: .boldSystemFont(ofSize: 22), after: 4))
        out.append(
            paragraph(
                "The Knowledge Press -- \(conversation.createdAt.formatted(dateStyle))",
                font: italic(body), color: gray, after: 18))

        for turn in conversation.turns {
            out.append(render(turn, image: image(turn), page: page))
        }

        out.append(
            paragraph(
                "Generated by The Knowledge Press. Passages are from public-domain texts; "
                    + "scores are the retrieval engine's own.",
                font: italic(PlatformFont.systemFont(ofSize: 9)), color: gray, before: 12))
        return out
    }

    private static func render(_ turn: ChatTurn, image: Data?, page: CGSize) -> NSAttributedString {
        let out = NSMutableAttributedString()
        out.append(paragraph(turn.question, font: .boldSystemFont(ofSize: 16), before: 6, after: 2))

        var provenance = ["scope: \(turn.corpus)", "engine: \(turn.engine.label)"]
        if let model = turn.metrics?.model { provenance.append(model) }
        out.append(
            paragraph(
                provenance.joined(separator: " -- "), font: PlatformFont.systemFont(ofSize: 9),
                color: gray, after: 8))

        if !turn.answer.isEmpty {
            out.append(answer(turn.answer))
        } else if let failure = turn.synthesisFailure {
            out.append(paragraph(failure.displayMessage, font: italic(body), color: gray, after: 8))
        } else if let error = turn.errorMessage {
            out.append(paragraph(error, font: italic(body), color: gray, after: 8))
        } else if turn.engine == .off {
            out.append(
                paragraph(
                    "Answer generation was off; the passages follow.", font: italic(body),
                    color: gray, after: 8))
        }

        if let image, let attachment = attachment(image, page: page) {
            let picture = NSMutableAttributedString(attachment: attachment)
            picture.append(NSAttributedString(string: "\n"))
            picture.addAttribute(
                .paragraphStyle, value: style(before: 4, after: 10),
                range: NSRange(location: 0, length: picture.length))
            out.append(picture)
        }

        let hits = turn.retrieval?.hits ?? []
        if !hits.isEmpty {
            out.append(sources(hits, metrics: turn.metrics))
        }
        return out
    }

    /// The answer's Markdown, keeping bold, italic and code spans and its
    /// own line breaks; block syntax such as `- ` stays as the text it is.
    private static func answer(_ markdown: String) -> NSAttributedString {
        let parsed =
            (try? AttributedString(
                markdown: markdown,
                options: .init(interpretedSyntax: .inlineOnlyPreservingWhitespace)))
            ?? AttributedString(markdown)

        let out = NSMutableAttributedString()
        for run in parsed.runs {
            let intent = run.inlinePresentationIntent ?? []
            var font = body
            if intent.contains(.code) {
                font = .monospacedSystemFont(ofSize: 10, weight: .regular)
            } else if intent.contains(.stronglyEmphasized) && intent.contains(.emphasized) {
                font = italic(.boldSystemFont(ofSize: body.pointSize))
            } else if intent.contains(.stronglyEmphasized) {
                font = .boldSystemFont(ofSize: body.pointSize)
            } else if intent.contains(.emphasized) {
                font = italic(body)
            }
            out.append(
                NSAttributedString(
                    string: String(parsed[run.range].characters), attributes: [.font: font]))
        }
        out.append(NSAttributedString(string: "\n"))
        out.addAttribute(
            .paragraphStyle, value: style(after: 8, lineSpacing: 2),
            range: NSRange(location: 0, length: out.length))
        return out
    }

    private static func sources(_ hits: [Hit], metrics: SynthesisMetrics?) -> NSAttributedString {
        let quoted = hits.prefix(ConversationMarkdown.quotedPassages)
        var heading = "Sources (\(hits.count) retrieved"
        if let used = metrics?.passagesUsed, used < hits.count {
            heading += ", \(used) reached the model"
        }
        if hits.count > quoted.count {
            heading += "; \(quoted.count) quoted"
        }
        heading += ")"

        let out = NSMutableAttributedString()
        out.append(
            paragraph(heading, font: .boldSystemFont(ofSize: 11), before: 4, after: 4))
        for hit in quoted {
            var attribution = hit.title ?? hit.name
            if let author = hit.author, !author.isEmpty { attribution += " -- \(author)" }
            let line = NSMutableAttributedString(
                string: "\u{2022} \(attribution)",
                attributes: [.font: PlatformFont.boldSystemFont(ofSize: 10)])
            line.append(
                NSAttributedString(
                    string:
                        " (\(hit.genre ?? hit.kgName), score \(ConversationMarkdown.score(hit.score)))\n",
                    attributes: [.font: PlatformFont.systemFont(ofSize: 10), .foregroundColor: gray]))
            line.addAttribute(
                .paragraphStyle, value: style(after: 2),
                range: NSRange(location: 0, length: line.length))
            out.append(line)
            if let text = ConversationMarkdown.passage(hit) {
                out.append(
                    paragraph(
                        text, font: italic(PlatformFont.systemFont(ofSize: 10)), color: gray,
                        after: 6, indent: 14))
            }
        }
        return out
    }

    // MARK: - Pieces

    private static func paragraph(
        _ text: String, font: PlatformFont, color: PlatformColor? = nil,
        before: CGFloat = 0, after: CGFloat = 0, indent: CGFloat = 0
    ) -> NSAttributedString {
        var attributes: [NSAttributedString.Key: Any] = [
            .font: font, .paragraphStyle: style(before: before, after: after, indent: indent),
        ]
        if let color { attributes[.foregroundColor] = color }
        return NSAttributedString(string: text + "\n", attributes: attributes)
    }

    private static func style(
        before: CGFloat = 0, after: CGFloat = 0, indent: CGFloat = 0, lineSpacing: CGFloat = 0
    ) -> NSParagraphStyle {
        let style = NSMutableParagraphStyle()
        style.paragraphSpacingBefore = before
        style.paragraphSpacing = after
        style.firstLineHeadIndent = indent
        style.headIndent = indent
        style.lineSpacing = lineSpacing
        return style
    }

    private static func italic(_ font: PlatformFont) -> PlatformFont {
        #if canImport(UIKit)
            let traits = font.fontDescriptor.symbolicTraits.union(.traitItalic)
            guard let descriptor = font.fontDescriptor.withSymbolicTraits(traits) else { return font }
            return UIFont(descriptor: descriptor, size: font.pointSize)
        #else
            return NSFontManager.shared.convert(font, toHaveTrait: .italicFontMask)
        #endif
    }

    /// The illustration, scaled to the text width and never taller than half
    /// a page -- an attachment taller than a page would never fit a container
    /// and pagination would stall on it.
    private static func attachment(_ data: Data, page: CGSize) -> NSTextAttachment? {
        guard let image = PlatformImage(data: data), image.size.width > 0 else { return nil }
        let contentSize = contentSize(page)
        let scale = min(contentSize.width / image.size.width, contentSize.height / 2 / image.size.height)
        let attachment = NSTextAttachment()
        attachment.image = image
        attachment.bounds = CGRect(
            x: 0, y: 0, width: image.size.width * scale, height: image.size.height * scale)
        return attachment
    }

    // MARK: - Pages

    private static func paginate(_ text: NSAttributedString, page pageSize: CGSize) -> Data {
        let storage = NSTextStorage(attributedString: text)
        let layout = NSLayoutManager()
        storage.addLayoutManager(layout)

        var pages: [NSRange] = []
        while true {
            let container = NSTextContainer(size: contentSize(pageSize))
            container.lineFragmentPadding = 0
            layout.addTextContainer(container)
            let range = layout.glyphRange(for: container)
            // An empty page means nothing more will fit; stop rather than
            // add containers forever.
            guard range.length > 0 else { break }
            pages.append(range)
            if NSMaxRange(range) >= layout.numberOfGlyphs { break }
        }

        let origin = CGPoint(x: margin, y: margin)
        let bounds = CGRect(origin: .zero, size: pageSize)
        #if canImport(UIKit)
            return UIGraphicsPDFRenderer(bounds: bounds).pdfData { context in
                for range in pages {
                    context.beginPage()
                    layout.drawBackground(forGlyphRange: range, at: origin)
                    layout.drawGlyphs(forGlyphRange: range, at: origin)
                }
            }
        #else
            let data = NSMutableData()
            var mediaBox = bounds
            guard let consumer = CGDataConsumer(data: data as CFMutableData),
                let context = CGContext(consumer: consumer, mediaBox: &mediaBox, nil)
            else { return Data() }
            let previous = NSGraphicsContext.current
            for range in pages {
                context.beginPDFPage(nil)
                // AppKit text draws top-down; flip the page to match.
                context.translateBy(x: 0, y: pageSize.height)
                context.scaleBy(x: 1, y: -1)
                NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: true)
                layout.drawBackground(forGlyphRange: range, at: origin)
                layout.drawGlyphs(forGlyphRange: range, at: origin)
                context.endPDFPage()
            }
            NSGraphicsContext.current = previous
            context.closePDF()
            return data as Data
        #endif
    }
}
